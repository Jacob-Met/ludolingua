import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { startReceiver } from '../serve.mjs';
import { readExport } from '../lib/export.mjs';

if (!process.env.PLAYWRIGHT_PACKAGE || !process.env.LUDO_EVIDENCE_DIR) throw new Error('Set PLAYWRIGHT_PACKAGE and LUDO_EVIDENCE_DIR to existing runtime package and evidence destination.');
const evidenceDir = resolve(process.env.LUDO_EVIDENCE_DIR);
await mkdir(evidenceDir, { recursive: true });
const { chromium } = await import(pathToFileURL(resolve(process.env.PLAYWRIGHT_PACKAGE, 'index.mjs')).href);
const { server, url } = await startReceiver();
let browser, page;
const receipt = { schema: 'ludolingua.browser-receiving.v1', startedAt: new Date().toISOString(), url, checks: [], errors: [], failedRequests: [], sandbox: null, passed: false };
const check = name => receipt.checks.push(name);
try {
  browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/google-chrome-stable', chromiumSandbox: true, args: ['--disable-dev-shm-usage', '--enable-automation'] });
  const session = await browser.newBrowserCDPSession();
  const command = await session.send('Browser.getBrowserCommandLine');
  assert.equal(command.arguments.some(a => a === '--no-sandbox' || a === '--disable-setuid-sandbox'), false, 'Sandbox-disabling launch flag');
  const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1280, height: 1000 }, acceptDownloads: true });
  page = await context.newPage();
  await page.goto('chrome://sandbox');
  const sandboxText = await page.locator('body').innerText();
  receipt.sandbox = { launchFlags: command.arguments, status: sandboxText };
  assert.match(sandboxText, /Seccomp-BPF sandbox\s+Yes/i, 'Seccomp sandbox not verified');
  check('Chromium sandbox status and launch arguments verified');
  page.on('pageerror', error => receipt.errors.push(String(error)));
  page.on('console', message => { if (message.type() === 'error') receipt.errors.push(message.text()); });
  page.on('requestfailed', request => receipt.failedRequests.push({ url: request.url(), error: request.failure()?.errorText }));
  await page.goto(url);
  await page.locator('#case-select option').first().waitFor({ state: 'attached' });
  await page.selectOption('#case-select', 'en-original');
  await page.click('#check-button');
  await page.locator('.result-state.verified').waitFor();
  assert.deepEqual(await page.locator('.metric strong').allTextContents(), ['1', '1', '24']);
  check('English receiver reports one clue order, one action match, all 24 permutations');
  await page.click('#player-tab');
  assert.equal(await page.locator('#result').isVisible(), false);
  assert.equal(await page.locator('#reveal').isVisible(), false);
  assert.doesNotMatch(await page.locator('body').innerText(), /\bOPEN\b/);
  await page.fill('#answer', 'OPEN'); await page.locator('#answer').press('Enter');
  await page.locator('#player-feedback').filter({ hasText: 'does not yet satisfy' }).waitFor();
  assert.equal(await page.locator('#reveal').isVisible(), false);
  await page.getByRole('button', { name: 'Move Nest down', exact: true }).focus();
  for (let i = 0; i < 3; i++) { await page.keyboard.press('Space'); assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), i < 2 ? 'Move Nest down' : 'Move Nest up'); }
  assert.deepEqual(await page.locator('.keeper-label').allTextContents(), ['Otter', 'Pine', 'Eagle', 'Nest']);
  await page.fill('#answer', 'CLOSE'); await page.locator('#answer').press('Enter');
  assert.equal(await page.locator('#player-feedback').textContent(), 'The order fits the clues. Try the action again using its initials.');
  assert.doesNotMatch(await page.locator('body').innerText(), /\bOPEN\b/);
  await page.fill('#answer', 'open'); await page.locator('#answer').press('Enter');
  await page.locator('#player-feedback').filter({ hasText: 'The action works' }).waitFor();
  await page.click('#hint-button'); assert.equal(await page.locator('#hints p').count(), 1);
  check('Player hides solution across visible page; wrong order and wrong action rejected; keyboard focus retained; normalized answer and deliberate hint work');
  {
    const enRetry = 'The order fits the clues. Try the action again using its initials.';
    const esRetry = 'El orden cumple las pistas. Intenta de nuevo la acción usando sus iniciales.';
    const esMismatch = 'El orden cumple las pistas, pero la acción no coincide. Esta adaptación puede necesitar cambios.';
    const feedback = async () => (await page.locator('#player-feedback').innerText()).trim();
    const choosePlayerCase = async id => { await page.selectOption('#case-select', id); await page.selectOption('#ui-language', id.startsWith('es-') ? 'es' : 'en'); await page.click('#player-tab'); };
    const submitAnswer = async answer => { await page.fill('#answer', answer); await page.locator('#answer').press('Enter'); };
    const solveFromInitialOrder = async (buttonName, expectedLabels) => {
      await page.getByRole('button', { name: buttonName, exact: true }).focus();
      for (let move = 0; move < 3; move += 1) await page.keyboard.press('Space');
      assert.deepEqual(await page.locator('.keeper-label').allTextContents(), expectedLabels);
    };
    const assertTargetConcealed = async target => assert.equal(new RegExp('\\b' + target + '\\b').test(await page.locator('body').innerText()), false, target + ' must remain concealed before success or reveal');
    await choosePlayerCase('en-original');
    assert.equal(await feedback(), '');
    await submitAnswer('OPEN');
    assert.equal(await feedback(), 'This order does not yet satisfy all the clues.');
    check('Clue-invalid English order retains clue guidance before answer retry');
    await page.click('#reset-order'); assert.equal(await feedback(), '');
    await solveFromInitialOrder('Move Nest down', ['Otter', 'Pine', 'Eagle', 'Nest']);
    for (const answer of ['CLOSE', '']) {
      await submitAnswer(answer); assert.equal(await feedback(), enRetry); await assertTargetConcealed('OPEN');
    }
    check('English wrong or empty typed answers receive retry guidance without target disclosure');
    await page.screenshot({ path: resolve(evidenceDir, 'feedback-english-desktop.png'), fullPage: true });
    await page.click('#reset-order'); assert.equal(await feedback(), '');
    assert.deepEqual(await page.locator('.keeper-label').allTextContents(), ['Nest', 'Otter', 'Pine', 'Eagle']);
    await submitAnswer('OPEN'); assert.equal(await feedback(), 'This order does not yet satisfy all the clues.');
    check('Order reset clears retry feedback and restores clue-first evaluation');
    await choosePlayerCase('es-adapted'); assert.equal(await feedback(), ''); await assertTargetConcealed('ABRE');
    await solveFromInitialOrder('Bajar Estrella', ['Agua', 'Barco', 'Roca', 'Estrella']);
    await submitAnswer('ABRA'); assert.equal(await feedback(), esRetry); await assertTargetConcealed('ABRE');
    check('Adapted Spanish wrong answer receives localized retry without target disclosure');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true, 'Retry feedback overflows the narrow player');
    await page.screenshot({ path: resolve(evidenceDir, 'feedback-spanish-narrow.png'), fullPage: true });
    await page.setViewportSize({ width: 1280, height: 1000 });
    await submitAnswer(' abre '); assert.equal(await feedback(), 'La acción funciona. El orden cumple las pistas y sus iniciales coinciden.');
    check('Corrected normalized Spanish answer succeeds after retry');
    await choosePlayerCase('es-literal'); assert.equal(await feedback(), '');
    await solveFromInitialOrder('Bajar Nido', ['Nutria', 'Pino', 'Águila', 'Nido']);
    await submitAnswer('ABRE'); assert.equal(await feedback(), esMismatch);
    await submitAnswer('NPÁN'); assert.equal(await feedback(), esMismatch);
    check('Literal Spanish keeps its adaptation diagnosis for both intended action and mismatched initials');
    await page.click('#reset-order'); assert.equal(await feedback(), '');
    assert.deepEqual(await page.locator('.keeper-label').allTextContents(), ['Nido', 'Nutria', 'Pino', 'Águila']);
    await submitAnswer('ABRE'); assert.equal(await feedback(), 'Este orden todavía no cumple todas las pistas.');
    check('Literal Spanish clue-invalid order retains clue guidance before adaptation diagnosis');
    await choosePlayerCase('en-original'); assert.equal(await feedback(), ''); await assertTargetConcealed('OPEN');
    assert.deepEqual(await page.locator('.keeper-label').allTextContents(), ['Nest', 'Otter', 'Pine', 'Eagle']);
    check('Case switch clears stale feedback and restores concealed English state');
  }
  await page.click('#author-tab'); await page.selectOption('#case-select', 'es-literal'); await page.click('#check-button');
  await page.locator('.result-state.action-mismatch').waitFor();
  assert.deepEqual(await page.locator('.metric strong').allTextContents(), ['1', '0', '24']);
  assert.equal(await page.locator('.token').first().textContent(), 'NPÁN');
  check('Literal Spanish preserves ordering but fails the action with accented initials retained');
  await page.selectOption('#case-select', 'es-adapted'); await page.click('#check-button'); await page.locator('.result-state.verified').waitFor();
  await page.fill('#label-2', 'Piedra'); assert.equal(await page.locator('#export-button').isDisabled(), true);
  await page.click('#check-button'); await page.locator('.result-state.action-mismatch').waitFor(); assert.equal(await page.locator('.token').first().textContent(), 'ABPE');
  const editedEvent = page.waitForEvent('download'); await page.click('#export-button'); const editedDownload = await editedEvent;
  const editedPath = resolve(evidenceDir, 'edited-negative-downloaded.json'); await editedDownload.saveAs(editedPath);
  const editedReceived = await readExport(await readFile(editedPath, 'utf8'));
  assert.equal(editedReceived.episode.cards[2].label, 'Piedra'); assert.equal(editedReceived.validation.result.mechanicalSuccess, false); assert.equal(editedReceived.validation.result.solutions[0].token, 'ABPE');
  await page.fill('#label-2', 'Roca'); await page.click('#check-button'); await page.locator('.result-state.verified').waitFor();
  check('Editing Roca to Piedra invalidates success and export; current check returns ABPE; explicit repair rechecks');
  const downloadEvent = page.waitForEvent('download'); await page.click('#export-button'); const download = await downloadEvent;
  const downloadedPath = resolve(evidenceDir, 'episode-downloaded.json'); await download.saveAs(downloadedPath);
  const source = JSON.parse(await readFile(downloadedPath, 'utf8')); const received = await readExport(source);
  assert.equal(received.integrity.verified, true); assert.equal(received.validation.result.mechanicalSuccess, true); assert.equal(received.episode.cards[2].label, 'Roca');
  receipt.download = { file: 'episode-downloaded.json', episodeSha256: received.integrity.episodeSha256, revision: received.episode.revision };
  await page.setInputFiles('#import-file', downloadedPath); await page.locator('#notice').filter({ hasText: 'Source digest and mechanical result verified' }).waitFor();
  assert.equal(await page.locator('#label-2').inputValue(), 'Roca'); assert.equal(await page.locator('#revision').textContent(), `Revision ${received.episode.revision}`);
  const tampered = structuredClone(source); tampered.episode.cards[2].label = 'Piedra';
  const badPath = resolve(evidenceDir, 'tampered-export.json'); await writeFile(badPath, JSON.stringify(tampered));
  await page.setInputFiles('#import-file', badPath); await page.locator('#notice.error').filter({ hasText: 'Cannot reopen:' }).waitFor();
  assert.equal(await page.locator('#label-2').inputValue(), 'Roca');
  check('Actual downloaded file verifies and reopens; changed content with old validation is rejected without replacing current episode');
  await page.click('#player-tab'); assert.doesNotMatch(await page.locator('body').innerText(), /\bABRE\b/); await page.click('#author-tab');
  await page.evaluate(() => { const original = File.prototype.text; File.prototype.text = function () { const file = this; return new Promise(resolveRead => { window.releaseLudoImportRead = () => { File.prototype.text = original; original.call(file).then(resolveRead); }; }); }; });
  await page.setInputFiles('#import-file', downloadedPath); await page.waitForFunction(() => typeof window.releaseLudoImportRead === 'function');
  await page.fill('#label-1', 'Bote'); await page.evaluate(() => { window.releaseLudoImportRead(); delete window.releaseLudoImportRead; });
  await page.locator('#notice.error').filter({ hasText: 'episode changed while this file was being verified' }).waitFor(); assert.equal(await page.locator('#label-1').inputValue(), 'Bote');
  check('Reopened Spanish player hides target; controlled pending file read cannot overwrite an intervening edit');
  await page.selectOption('#case-select', 'es-frozen'); await page.click('#check-button'); await page.locator('.witness').waitFor();
  assert.equal(await page.locator('#label-0').isDisabled(), true); assert.match(await page.locator('.witness').innerText(), /B.*R.*E/);
  const negativeEvent = page.waitForEvent('download'); await page.click('#export-button'); const negative = await negativeEvent; const negativePath = resolve(evidenceDir, 'frozen-downloaded.json'); await negative.saveAs(negativePath);
  const negativeReceived = await readExport(await readFile(negativePath, 'utf8')); assert.equal(negativeReceived.integrity.verified, true); assert.equal(negativeReceived.validation.result.mechanicalSuccess, false); assert.ok(negativeReceived.validation.result.frozenWitness);
  await page.uncheck('#freeze-labels'); assert.equal(await page.locator('#label-0').isDisabled(), false); assert.equal(await page.locator('#export-button').isDisabled(), true); assert.equal(await page.locator('.witness').count(), 0); assert.equal(await page.locator('#revision').textContent(), 'Revision 2');
  check('Frozen-label witness survives actual export while keeping failure distinct from verified integrity');
  await page.selectOption('#case-select', 'en-ambiguous'); await page.click('#check-button'); await page.locator('.result-state.ambiguous').waitFor(); assert.deepEqual(await page.locator('.metric strong').allTextContents(), ['12', '1', '24']);
  await page.selectOption('#case-select', 'en-contradictory'); await page.click('#check-button'); await page.locator('.result-state.inconsistent').waitFor(); assert.deepEqual(await page.locator('.metric strong').allTextContents(), ['0', '0', '24']);
  check('Ambiguous 12-order and inconsistent zero-order outcomes remain distinct in actual receiver');
  await page.fill('#label-0', ''); await page.click('#check-button'); await page.locator('.result-state.invalid').waitFor(); assert.equal(await page.locator('#export-button').isDisabled(), true);
  check('Incomplete label edits produce an invalid result without browser exceptions or stale export');
  await page.selectOption('#case-select', 'es-adapted'); await page.click('#check-button'); await page.locator('.result-state.verified').waitFor();
  await page.screenshot({ path: resolve(evidenceDir, 'receiver-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true, 'Narrow view overflows');
  await page.screenshot({ path: resolve(evidenceDir, 'receiver-narrow.png'), fullPage: true });
  await page.locator('#author-tab').focus(); await page.locator('#author-tab').press('ArrowRight'); assert.equal(await page.locator('#player').isVisible(), true);
  assert.doesNotMatch(await page.locator('body').innerText(), /\bABRE\b/);
  await page.selectOption('#ui-language', 'es');
  await page.getByRole('button', { name: 'Bajar Estrella', exact: true }).focus();
  for (let i = 0; i < 3; i++) { await page.keyboard.press('Space'); assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), i < 2 ? 'Bajar Estrella' : 'Subir Estrella'); }
  await page.fill('#answer', 'abre'); await page.locator('#answer').press('Enter'); await page.locator('#player-feedback').filter({ hasText: 'La acción funciona' }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
  await page.screenshot({ path: resolve(evidenceDir, 'player-narrow.png'), fullPage: true });
  check('390px receiver/player fit without horizontal overflow; keyboard tab selection and Spanish play course succeed');
  assert.deepEqual(receipt.errors, []); assert.deepEqual(receipt.failedRequests, []); check('No console errors, page errors or failed requests');
  receipt.passed = true;
} catch (error) {
  receipt.failure = { message: error.message, stack: error.stack };
  if (page) await page.screenshot({ path: resolve(evidenceDir, 'failure.png'), fullPage: true }).catch(() => {});
  process.exitCode = 1;
} finally {
  receipt.finishedAt = new Date().toISOString();
  if (browser) await browser.close();
  await new Promise(done => server.close(done));
  await writeFile(resolve(evidenceDir, 'receipt.json'), JSON.stringify(receipt, null, 2) + '\n');
  console.log(JSON.stringify(receipt));
}
